export type LocalizedString = string & { readonly __brand: unique symbol }

export function t(key: string, lang: Language = 'en', vars: Record<string, string | number> = {}): LocalizedString {
  let text = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en'][key] || key
  
  for (const [
    k,
    v,
  ] of Object.entries(vars)) {
    text = text.replace(`{${k}}`, String(v))
  }
  
  return text as LocalizedString
}

export function l(strings: TemplateStringsArray, ...values: (LocalizedString | number | boolean | null | undefined)[]): LocalizedString {
  let result = ''
  for (let i = 0; i < strings.length; i++) {
    result += strings[i]
    if (i < values.length) {
      result += String(values[i])
    }
  }
  return result as LocalizedString
}

export const local = (str: string) => str as LocalizedString
export const num = (value: number, decimals = 2) => value.toFixed(decimals) as LocalizedString
export const price = (value: number) => `$${value.toFixed(2)}` as LocalizedString

